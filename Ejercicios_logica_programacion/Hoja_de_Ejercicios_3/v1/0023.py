#Que pida un número del 1 al 12 y diga el nombre del mes correspondiente

#Entrada
num_mes = int(input('Introduce un numero del mes:\n'))
#Proceso
if num_mes == 1:
    print('Enero')
elif num_mes == 2:
    print('Febrero')
elif num_mes == 3:
    print('Marzo')
elif num_mes == 4:
    print('Abril')
elif num_mes == 5:
    print('Mayo')
elif num_mes == 6:
    print('Junio')
elif num_mes == 7:
    print('Julio')
elif num_mes == 8:
    print('Agosto')
elif num_mes == 9:
    print('Setiembre')
elif num_mes == 10:
    print('Octubre')
elif num_mes == 11:
    print('Noviembre')
elif num_mes == 12:
    print('Diciembre')
else:
    print('No corresponde a ningun numero del mes.')
